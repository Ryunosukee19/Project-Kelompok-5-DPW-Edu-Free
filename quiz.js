let currentSoal = [];

const btnMulai = document.getElementById("btn-mulai-kuis");
const selectSemester = document.getElementById("pilih-semester");
const selectMatkul = document.getElementById("pilih-matkul");
const matkulContainer = document.getElementById("matkul-container");
const formKuis = document.getElementById("form-kuis");
const formKuisioner = document.getElementById("form-kuisioner");

selectSemester.addEventListener("change", (e) => {
  const sem = e.target.value;
  selectMatkul.innerHTML = '<option value="">-- Pilih Matkul --</option>';

  if (sem === "1") {
    matkulContainer.style.display = "block";
    selectMatkul.innerHTML += `
            <option value="Alpro">Algoritma & Pemrograman (Alpro)</option>
            <option value="PTI">Pengantar Teknologi Informasi (PTI)</option>
        `;
  } else if (sem === "2") {
    matkulContainer.style.display = "block";
    selectMatkul.innerHTML += `
            <option value="DPW">Dasar Pemrograman Web (DPW)</option>
            <option value="Struktur Data">Struktur Data</option>
        `;
  } else {
    matkulContainer.style.display = "none";
  }
});

btnMulai.addEventListener("click", () => {
  const semester = selectSemester.value;
  const matkul = selectMatkul.value;

  if (semester === "" || matkul === "") {
    alert("Pilih semester dan mata kuliah terlebih dahulu!");
    return;
  }

  currentSoal = bankSoal[semester].filter((soal) => soal.matkul === matkul);

  document.getElementById("error-7").style.display = "none";
  document.getElementById("content-7").style.display = "block";

  document.getElementById("content-8").style.display = "none";
  document.getElementById("error-8").style.display = "flex";

  document.getElementById("content-9").style.display = "none";
  document.getElementById("error-9").style.display = "flex";

  document.getElementById("kuisioner-container").style.display = "block";
  document.getElementById("pembahasan-asli").style.display = "none";

  if (document.getElementById("form-kuisioner")) {
    document.getElementById("form-kuisioner").reset();
    document.getElementById("rating-val").innerText = "5";
  }

  renderSoal();
  document.getElementById("soal-kuis").scrollIntoView({ behavior: "smooth" });
});

function renderSoal() {
  const container = document.getElementById("quiz-container");
  container.innerHTML = "";

  currentSoal.forEach((soal, index) => {
    const no = index + 1;
    const fieldset = document.createElement("fieldset");
    fieldset.className = "quiz-question";
    fieldset.style.marginBottom = "15px";

    let optionsHTML = "";
    for (const [key, val] of Object.entries(soal.options)) {
      const textAman = val.replace(/</g, "&lt;").replace(/>/g, "&gt;");

      optionsHTML += `
                <input type="radio" id="p${no}${key}" name="q${no}" value="${key}" required>
                <label for="p${no}${key}">${key.toUpperCase()}. ${textAman}</label><br>
            `;
    }

    fieldset.innerHTML = `
            <legend><b>No ${no}</b></legend>
            <p>${soal.q.replace(/</g, "&lt;").replace(/>/g, "&gt;")}</p>
            ${optionsHTML}
        `;
    container.appendChild(fieldset);
  });
}

formKuis.addEventListener("submit", (e) => {
  e.preventDefault();

  let benar = 0;
  const total = currentSoal.length;

  currentSoal.forEach((soal, index) => {
    const no = index + 1;
    const userAnswer = document.querySelector(`input[name="q${no}"]:checked`);

    if (userAnswer && userAnswer.value === soal.ans) {
      benar++;
    }
  });

  const skorAkhir = Math.round((benar / total) * 100);

  document.getElementById("error-8").style.display = "none";
  document.getElementById("content-8").style.display = "block";

  document.getElementById("error-9").style.display = "none";
  document.getElementById("content-9").style.display = "block";

  document.getElementById("nilai-akhir").innerText = skorAkhir;
  document.getElementById("jawaban-benar").innerText = benar;
  document.getElementById("total-soal").innerText = total;

  renderPembahasan();
  document.getElementById("skor-akhir").scrollIntoView({ behavior: "smooth" });
});

function renderPembahasan() {
  const container = document.getElementById("pembahasan-container");
  container.innerHTML = "";

  currentSoal.forEach((soal, index) => {
    const no = index + 1;
    const bahasAman = soal.bahas.replace(/</g, "&lt;").replace(/>/g, "&gt;");

    container.innerHTML += `
            <dt><span class="answer-badge">${no}</span> Jawaban ${soal.ans.toUpperCase()}</dt>
            <dd>${bahasAman}</dd>
        `;
  });
}

formKuisioner.addEventListener("submit", (e) => {
  e.preventDefault();
  document.getElementById("kuisioner-container").style.display = "none";
  document.getElementById("pembahasan-asli").style.display = "block";
  alert("Terima kasih atas masukannya!");
});
